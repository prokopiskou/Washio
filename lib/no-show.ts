import { athensEpoch } from '@/lib/time'

// Παράθυρο «Δεν εμφανίστηκε» (no-show) για το πλυντήριο:
// το κουμπί ανοίγει 15' μετά την ώρα του ραντεβού και μένει μέχρι το ΤΕΛΟΣ ΤΗΣ ΗΜΕΡΑΣ του ραντεβού
// (23:59 ώρα Ελλάδας). Όταν αλλάξει η μέρα, το κουμπί φεύγει.
// Αν δεν πατηθεί μέχρι τότε, η κράτηση μετράει ως ολοκληρωμένη.
export const NO_SHOW_FROM_MIN = 15
export const NO_SHOW_UNTIL_MIN = 5 * 60

/** Μέχρι πότε (epoch ms) επιτρέπεται το «Δεν εμφανίστηκε»: ΑΥΣΤΗΡΑ μέχρι τα μεσάνυχτα της ημέρας του ραντεβού.
 *  (Πριν: και τουλάχιστον 5 ώρες → σε βραδινά ραντεβού το κουμπί έμενε και την επόμενη μέρα.) */
export function noShowDeadline(slotDate: string, _slotStartTime?: string): number {
  return athensEpoch(slotDate, '23:59') + 59_000
}
